// --- Functions ---

function applyIAESTranslations(lang) {
  const t = iaesTranslations[lang] || iaesTranslations['en'];
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (t[key]) {
      if (el.children.length > 0 && !el.closest('li')) {
        el.innerHTML = t[key];
      } else if (el.tagName === 'LI' || el.children.length > 0) {
        el.innerHTML = t[key];
      } else {
        el.textContent = t[key];
      }
    }
  });
  // RTL support for Arabic
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}

function initIAESI18n() {
  var saved = localStorage.getItem('wertek-lang') || 'en';
  var select = document.getElementById('iaes-lang-select');
  if (select) {
    select.value = saved;
    applyIAESTranslations(saved);
    select.addEventListener('change', function() {
      localStorage.setItem('wertek-lang', this.value);
      applyIAESTranslations(this.value);
    });
  }
}

document.addEventListener('DOMContentLoaded', initIAESI18n);
